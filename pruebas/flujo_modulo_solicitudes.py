# Prueba del módulo de Solicitudes: crear (autocompletar, ruteo, duplicado), validar, llegada, seguimiento, consulta por DUI
import sys, subprocess; sys.path.insert(0, '.')
from smoke import *

def sql(s):
    r = subprocess.run(['su', 'postgres', '-c', f'psql -d sigam -At -c "{s}"'], capture_output=True, text=True)
    return r.stdout.strip() or r.stderr.strip()
ok = lambda c, m: print(('  ✔ ' if c else '  ✘ ') + m)
def toast(pg, timeout=30000):
    pg.wait_for_selector('.toast', timeout=timeout); t = pg.inner_text('#toasts'); pg.evaluate("document.querySelector('#toasts').innerHTML=''"); return t

DUI = '011122233'
sql(f"delete from solicitud_eventos where solicitud_id in (select id from solicitudes where dui in ('{DUI}','044455566')); delete from solicitudes where dui in ('{DUI}','044455566'); delete from beneficiarios where dui in ('{DUI}','044455566'); delete from solicitud_responsables")
sql("insert into beneficiarios (dui, nombre, telefono, sector, departamento, sede_id) values ('044455566','ROSA PRUEBA MARTINEZ','71112222','FAES','Santa Ana',3) on conflict do nothing")
sql("insert into solicitud_responsables (tipo, area, email) values ('medicamento','DSEC','jose.avila@inabve.gob.sv'), ('medicamento','DSIN','iris.ramirez@inabve.gob.sv'), ('medicamento','SEGUIMIENTO','iris.ramirez@inabve.gob.sv'), ('insumo','DSEC','jose.avila@inabve.gob.sv'), ('insumo','DSIN','iris.ramirez@inabve.gob.sv')")

with sync_playwright() as p:
    br = p.chromium.launch(); errs = []
    print('1. Nueva solicitud de medicamento (primera vez) como dependiente')
    ctx = contexto(br, 'dep'); pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8080/#solicitudes?ver=nueva'); pg.wait_for_selector('.tipo-sol', timeout=60000)
    ok('Solicitudes' in pg.inner_text('nav'), 'el menú tiene Solicitudes')
    pg.click('.tipo-sol[data-tipo=medicamento]')
    pg.fill('.dui-grande', '044455566'); pg.wait_for_selector('.info-dui .ok', timeout=15000)
    ok(pg.input_value('input[placeholder="Nombre completo"]') == 'ROSA PRUEBA MARTINEZ', 'autocompleta el beneficiario por DUI')
    pg.fill('.dui-grande', DUI); pg.wait_for_selector('text=Beneficiario nuevo', timeout=15000)
    pg.fill('input[placeholder="Nombre completo"]', 'Carlos Prueba Hernández'); pg.fill('input[placeholder="7000 0000"]', '7000-1234')
    pg.click('text=Primera vez que lo solicita')
    ok('DSEC' in pg.inner_text('.destino-sol'), 'primera vez → avisa que va a DSEC: ' + pg.inner_text('.destino-sol')[:60])
    pg.fill('.bloque-sol input[type=search]', 'positral'); pg.wait_for_selector('.sugerencia'); pg.click('.sugerencia >> nth=0')
    pg.fill('input[placeholder=Cantidad]', '2')
    pg.locator('select').filter(has_text='Elija la justificación').select_option('Indicación de especialista')
    pg.screenshot(path='shots/s1_nueva.png', full_page=True)
    pg.click('text=Registrar solicitud'); t = toast(pg); ok('enviada a DSEC' in t, t)
    pg.wait_for_selector('.detalle-sol', timeout=15000); pg.screenshot(path='shots/s2_detalle.png')
    ok(pg.locator('.gestion-sol').count() == 0, 'DSIN no puede gestionar lo que espera al médico de DSEC')
    ok(sql(f"select area||'|'||estado||'|'||creado_por from solicitudes where dui='{DUI}'") == 'DSEC|registrada|iris.ramirez@inabve.gob.sv', 'guardada en DSEC, pendiente de validación')
    ok(int(sql("select count(*) from correo_cola where asunto like 'Nueva solicitud por validar%' and 'jose.avila@inabve.gob.sv' = any(para)")) >= 1, 'correo al responsable DSEC en la cola')
    pg.keyboard.press('Escape')

    print('2. Duplicado')
    pg.goto('http://localhost:8080/#solicitudes?ver=nueva'); pg.wait_for_selector('.tipo-sol'); pg.click('.tipo-sol[data-tipo=medicamento]')
    pg.fill('.dui-grande', DUI); pg.wait_for_selector('.info-dui .aviso-warn', timeout=15000)
    ok('solicitud(es) abierta(s)' in pg.inner_text('.info-dui'), 'avisa que ya tiene una solicitud abierta')
    pg.click('text=Primera vez que lo solicita'); pg.fill('.bloque-sol input[type=search]', 'positral'); pg.wait_for_selector('.sugerencia'); pg.click('.sugerencia >> nth=0')
    pg.locator('select').filter(has_text='Elija la justificación').select_option('Otro'); pg.fill('input[placeholder=Explique]', 'prueba')
    pg.click('text=Registrar solicitud'); pg.wait_for_selector('text=Ya tiene una solicitud abierta', timeout=15000)
    ok(True, 'pide confirmación antes de duplicar'); pg.click('.modal >> text=Cancelar')

    print('3. Insumo: preguntas de primera entrega y evaluación')
    pg.goto('http://localhost:8080/#solicitudes?ver=nueva'); pg.wait_for_selector('.tipo-sol'); pg.click('.tipo-sol[data-tipo=insumo]')
    pg.fill('.dui-grande', '044455566'); pg.wait_for_selector('.info-dui .ok', timeout=15000)
    pg.click('text=Sí, primera vez'); pg.locator('.segmentado').nth(1).locator('text=No').click()
    ok('DSEC' in pg.inner_text('.destino-sol'), 'sin evaluación médica → DSEC')
    pg.locator('.segmentado').nth(1).locator('text=Sí').click()
    ok('DSIN' in pg.inner_text('.destino-sol'), 'con evaluación → DSIN')
    pg.click('text=No está en el catálogo'); pg.fill('input[placeholder^="Descripción del insumo"]', 'Medias compresivas talla M'); pg.fill('input[placeholder=Cantidad]', '2')
    pg.locator('select').filter(has_text='Elija la justificación').select_option('Sin existencia en la sede')
    pg.screenshot(path='shots/s3_insumo.png', full_page=True)
    pg.click('text=Registrar solicitud'); t = toast(pg); ok('enviada a DSIN' in t, t)
    ctx.close()

    print('4. DSEC (José) valida')
    ctx = contexto(br, 'cons'); pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8080/#solicitudes'); pg.wait_for_selector('table', timeout=60000); pg.wait_for_timeout(1500)
    ok(pg.locator('a[data-ruta=solicitudes] .insignia:not(.oculto)').count() == 1, 'insignia con pendientes en el menú: ' + pg.inner_text('a[data-ruta=solicitudes]').replace('\n', ' '))
    pg.locator('.filtros select').first.select_option('validar'); pg.wait_for_timeout(800)
    pg.click(f'td:has-text("Carlos Prueba")'); pg.wait_for_selector('.detalle-sol')
    pg.locator('.modal button', has_text='Aprobar (finaliza)').click(); pg.wait_for_selector('.modal >> nth=1'); pg.fill('.modal >> nth=1 >> textarea', 'Procede según indicación de neumología')
    pg.locator('.modal').last.locator('button', has_text='Aceptar').click(); t = toast(pg); ok('validada' in t, t)
    ok(sql(f"select area||'|'||estado||'|'||validado_por from solicitudes where dui='{DUI}' and tipo='medicamento'") == 'DSEC|aprobada|jose.avila@inabve.gob.sv', 'DSEC aprueba y la gestión finaliza (no pasa a DSIN)')
    ok(sql(f"select cerrada_at is not null from solicitudes where dui='{DUI}' and tipo='medicamento'") == 't', 'queda cerrada')
    # para seguir probando la entrega: una de DSIN "Ya gestionado"
    sql(f"update solicitudes set area='DSIN', estado='en_gestion', cerrada_at=null where dui='{DUI}' and tipo='medicamento'")
    ok(int(sql("select count(*) from correo_cola where asunto like 'Solicitud validada%' and 'iris.ramirez@inabve.gob.sv' = any(para)")) >= 1, 'correo de confirmación a quien la registró')
    ctx.close()

    print('5. Llega el producto → seguimiento telefónico')
    sql(f"insert into lotes (producto_id, bodega_id, numero_lote, fecha_vencimiento, cantidad_inicial, disponible) select producto_id, 10, 'PRUEBA-SOL', '2028-01-01', 3, 3 from solicitudes where dui='{DUI}' and tipo='medicamento'")
    sql(f"select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000001',false); insert into movimientos (tipo, lote_id, producto_id, bodega_id, cantidad, documento) select 'entrada', l.id, l.producto_id, l.bodega_id, 3, 'factura' from lotes l join bodegas b on b.id=l.bodega_id where b.sede_id=3 and b.tipo='despacho_medicamentos' and l.producto_id=(select producto_id from solicitudes where dui='{DUI}' and tipo='medicamento') limit 1")
    ok(sql(f"select estado from solicitudes where dui='{DUI}' and tipo='medicamento'") == 'lista', 'quedó Lista para entregar')
    ctx = contexto(br, 'dep'); pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8080/#seguimiento'); pg.wait_for_selector('.tarjeta-llamada', timeout=60000)
    ok('ya llegó' in pg.inner_text('body').lower() and 'CARLOS' in pg.inner_text('body').upper(), 'aparece en "El producto ya llegó: avise"')
    pg.screenshot(path='shots/s4_seguimiento.png', full_page=True)
    card = pg.locator('.tarjeta-llamada', has_text='CARLOS')
    card.locator('input[placeholder=Nota]').fill('Pasará el lunes'); card.locator('text=Avisado: pasará a retirar').click(); t = toast(pg)
    ok(sql(f"select estado||'|'||intentos from solicitudes where dui='{DUI}' and tipo='medicamento'") == 'avisado|1', 'llamada registrada: avisado')

    print('6. Consulta por DUI')
    pg.goto('http://localhost:8080/#solicitudes?ver=dui'); pg.wait_for_selector('.dui-grande', timeout=30000)
    pg.fill('.dui-grande', DUI); pg.wait_for_selector('.consulta-sol', timeout=15000)
    ok('llamado, esperando retiro' in pg.inner_text('.lista-consulta'), 'muestra el estado: ' + pg.inner_text('.consulta-sol >> nth=0').split('\n')[1][:60])
    pg.screenshot(path='shots/s5_consulta.png', full_page=True)
    ctx.close()

    print('7. Administración: responsables y tablero')
    ctx = contexto(br, 'admin'); pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8080/#solicitudes?ver=responsables'); pg.wait_for_selector('.tabla-resp', timeout=60000)
    ok('José' in pg.inner_text('.tabla-resp') or 'jose' in pg.inner_text('.tabla-resp').lower(), 'tabla de responsables por tipo y área')
    pg.screenshot(path='shots/s6_responsables.png', full_page=True)
    pg.goto('http://localhost:8080/#tablero'); pg.wait_for_selector('.pestanas', timeout=30000); pg.click('.pestanas >> text=Solicitudes'); pg.wait_for_selector('.kpi', timeout=30000)
    ok(True, 'tablero: ' + pg.inner_text('.kpi >> nth=0').replace('\n', ' '))
    pg.screenshot(path='shots/s7_tablero.png', full_page=True)
    ctx.close()
    ok(not errs, f'sin errores JS {errs[:3]}')
    br.close()
