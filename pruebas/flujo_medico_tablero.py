from smoke import *
ok = lambda c, m: print(('  ✔ ' if c else '  ✘ ') + m)
def sql(s):
    r = subprocess.run(['su','postgres','-c',f'psql -d sigam -At -c "{s}"'],capture_output=True,text=True); return r.stdout.strip() or r.stderr.strip()
D='066600033'
