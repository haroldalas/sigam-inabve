-- 1. DUI: 9 dígitos sin guion -------------------------------------------------
create or replace function normalizar_dui(p text) returns text
language plpgsql immutable set search_path = public as $$
declare d text := regexp_replace(coalesce(p,''), '\D', '', 'g');
begin
  if length(d) <> 9 then
    raise exception 'DUI inválido: "%". Escriba los 9 dígitos, sin guion', coalesce(p,'');
  end if;
  return d;
end $$;

alter table salidas drop constraint salida_beneficiario_identificado;
alter table salidas add constraint salida_beneficiario_con_dui
  check (tipo <> 'beneficiario' or sifar_id is not null or dui ~ '^\d{9}$');
alter table devoluciones add constraint devolucion_dui_9 check (dui ~ '^\d{9}$');

-- 2. Bloqueo de lotes ---------------------------------------------------------
create table bloqueos_lote (
  id           bigint generated by default as identity primary key,
  lote_id      bigint not null references lotes(id),
  accion       text not null check (accion in ('bloqueado','cuarentena','liberado')),
  motivo       text not null,
  usuario      text,
  fecha        timestamptz not null default now()
);
create index on bloqueos_lote (lote_id);
alter table bloqueos_lote enable row level security;
create policy leer on bloqueos_lote for select to authenticated
  using (exists (select 1 from lotes l where l.id = lote_id));
grant select on bloqueos_lote to authenticated;

-- p_todas_sedes: aplica a todas las copias del mismo lote (misma factura, lote y vencimiento) en todas las bodegas
create or replace function bloquear_lote(p_lote bigint, p_estado estado_lote, p_motivo text, p_todas_sedes boolean default true)
returns int language plpgsql security definer set search_path = public as $$
declare o lotes; r record; n int := 0;
begin
  perform exigir(es_admin(), 'Solo un administrador bloquea lotes');
  perform exigir(p_estado in ('bloqueado','cuarentena'), 'Estado no válido');
  perform exigir(length(trim(coalesce(p_motivo,''))) >= 5, 'Indique el motivo del bloqueo');
  select * into o from lotes where id = p_lote;
  perform exigir(found, 'Lote no válido');
  for r in select id from lotes
            where id = p_lote
               or (p_todas_sedes and producto_id = o.producto_id
                   and numero_lote is not distinct from o.numero_lote
                   and fecha_vencimiento is not distinct from o.fecha_vencimiento)
            for update loop
    update lotes set estado = p_estado where id = r.id;
    insert into bloqueos_lote(lote_id, accion, motivo, usuario) values (r.id, p_estado::text, p_motivo, app_email());
    n := n + 1;
  end loop;
  return n;
end $$;

create or replace function liberar_lote(p_lote bigint, p_motivo text, p_todas_sedes boolean default true)
returns int language plpgsql security definer set search_path = public as $$
declare o lotes; r record; n int := 0;
begin
  perform exigir(es_admin(), 'Solo un administrador libera lotes');
  perform exigir(length(trim(coalesce(p_motivo,''))) >= 5, 'Indique el motivo de la liberación');
  select * into o from lotes where id = p_lote;
  for r in select id, disponible from lotes
            where estado in ('bloqueado','cuarentena')
              and (id = p_lote or (p_todas_sedes and producto_id = o.producto_id
                   and numero_lote is not distinct from o.numero_lote
                   and fecha_vencimiento is not distinct from o.fecha_vencimiento))
            for update loop
    update lotes set estado = case when r.disponible > 0 then 'activo' else 'agotado' end::estado_lote where id = r.id;
    insert into bloqueos_lote(lote_id, accion, motivo, usuario) values (r.id, 'liberado', p_motivo, app_email());
    n := n + 1;
  end loop;
  return n;
end $$;

-- 4. Bitácora de traslados ----------------------------------------------------
create or replace view v_bitacora_traslados with (security_invoker = true) as
select t.id, t.numero, t.fecha, t.estado,
       bo.nombre as bodega_origen, so.nombre as sede_origen, bd.nombre as bodega_destino, sd.nombre as sede_destino,
       categoria_reporte(null::tipo_producto, bd.tipo) as categoria_destino,
       t.enviado_por, t.enviado_at, t.recibido_por, t.recibido_at, t.anulado_por, t.motivo_anulacion, t.enviado_sivet,
       count(d.id) as lineas, sum(d.cantidad_enviada) as unidades_enviadas, sum(d.cantidad_recibida) as unidades_recibidas,
       round(sum(d.cantidad_enviada * lo.precio_unitario), 2) as monto,
       (select count(*) from traslado_diferencias df where df.traslado_id = t.id and df.estado = 'pendiente') as diferencias_pendientes,
       string_agg(distinct p.tipo::text, ', ') as tipos_producto,
       t.observaciones
  from traslados t
  join bodegas bo on bo.id = t.bodega_origen_id join sedes so on so.id = bo.sede_id
  join bodegas bd on bd.id = t.bodega_destino_id join sedes sd on sd.id = bd.sede_id
  left join traslado_detalle d on d.traslado_id = t.id
  left join lotes lo on lo.id = d.lote_origen_id
  left join productos p on p.id = d.producto_id
 group by t.id, bo.nombre, so.nombre, bd.nombre, sd.nombre, bd.tipo;

create or replace function marcar_enviado_sivet(p_traslados bigint[]) returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  perform exigir(es_admin(), 'Solo un administrador marca traslados como enviados a TICS');
  update traslados set enviado_sivet = true where id = any(p_traslados) and not enviado_sivet;
  get diagnostics n = row_count;
  return n;
end $$;

