create policy leer on conteo_detalle for select to authenticated
  using (exists (select 1 from conteos c where c.id = conteo_id and ((select es_admin()) or puede_operar_bodega(c.bodega_id))));
grant select on conteos, conteo_detalle to authenticated;

-- Abre el conteo de una bodega con la foto de existencias por lote
create or replace function iniciar_conteo(p_bodega smallint, p_observaciones text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_num text; n int;
begin
  perform exigir(puede_operar_bodega(p_bodega), 'No tiene permiso sobre esta bodega');
  perform exigir(not exists (select 1 from conteos where bodega_id = p_bodega and estado in ('en_proceso','pendiente_aprobacion')),
                 'Ya hay un conteo abierto en esta bodega');
  v_num := siguiente_numero('conteo', 'C-', 4);
  insert into conteos(numero, bodega_id, observaciones, creado_por) values (v_num, p_bodega, p_observaciones, app_email())
  returning id into v_id;
  insert into conteo_detalle(conteo_id, lote_id, producto_id, cantidad_sistema)
  select v_id, l.id, l.producto_id, l.disponible from lotes l
   where l.bodega_id = p_bodega and l.disponible > 0;
  get diagnostics n = row_count;
  return jsonb_build_object('conteo_id', v_id, 'numero', v_num, 'lotes', n);
end $$;

-- Registra lo contado de un lote. Si el lote no estaba en la foto (p. ej. agotado en sistema), se agrega.
create or replace function registrar_conteo(p_conteo bigint, p_lote bigint, p_cantidad numeric, p_observacion text default null)
returns void language plpgsql security definer set search_path = public as $$
declare c conteos; l lotes;
begin
  select * into c from conteos where id = p_conteo;
  perform exigir(found and c.estado = 'en_proceso', 'El conteo no está en proceso');
  perform exigir(puede_operar_bodega(c.bodega_id), 'No tiene permiso sobre esta bodega');
  perform exigir(p_cantidad is not null and p_cantidad >= 0, 'Cantidad inválida');
  select * into l from lotes where id = p_lote;
  perform exigir(found and l.bodega_id = c.bodega_id, 'El lote no pertenece a esta bodega');
  insert into conteo_detalle(conteo_id, lote_id, producto_id, cantidad_sistema, cantidad_fisica, contado_por, contado_at, observacion)
  values (p_conteo, p_lote, l.producto_id, l.disponible, p_cantidad, app_email(), now(), p_observacion)
  on conflict (conteo_id, lote_id) do update
    set cantidad_fisica = excluded.cantidad_fisica, contado_por = excluded.contado_por,
        contado_at = excluded.contado_at, observacion = coalesce(excluded.observacion, conteo_detalle.observacion);
end $$;

create or replace function finalizar_conteo(p_conteo bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare c conteos; v_sin int; v_dif int;
begin
  select * into c from conteos where id = p_conteo for update;
  perform exigir(found and c.estado = 'en_proceso', 'El conteo no está en proceso');
  perform exigir(puede_operar_bodega(c.bodega_id), 'No tiene permiso sobre esta bodega');
  select count(*) filter (where cantidad_fisica is null), count(*) filter (where diferencia <> 0)
    into v_sin, v_dif from conteo_detalle where conteo_id = p_conteo;
  update conteos set estado = 'pendiente_aprobacion', finalizado_por = app_email(), finalizado_at = now() where id = p_conteo;
  return jsonb_build_object('lotes_sin_contar', v_sin, 'lotes_con_diferencia', v_dif);
end $$;

-- Aprobación (administrador): aplica las diferencias como ajustes.
-- p_sin_contar_cero: los lotes no contados se toman como 0 (si no, se ignoran).
create or replace function aprobar_conteo(p_conteo bigint, p_obs text default null, p_sin_contar_cero boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c conteos; d record; v_fis numeric; v_delta numeric; v_aj bigint; n int := 0;
begin
  perform exigir(es_admin(), 'Solo un administrador aprueba conteos');
  select * into c from conteos where id = p_conteo for update;
  perform exigir(found and c.estado = 'pendiente_aprobacion', 'El conteo no está pendiente de aprobación');
  for d in select cd.*, l.disponible as actual from conteo_detalle cd join lotes l on l.id = cd.lote_id
            where cd.conteo_id = p_conteo for update of l loop
    v_fis := coalesce(d.cantidad_fisica, case when p_sin_contar_cero then 0 end);
    continue when v_fis is null;
    v_delta := v_fis - d.cantidad_sistema;          -- diferencia respecto de la foto
    continue when v_delta = 0;
    v_delta := greatest(v_delta, -d.actual);         -- no dejar existencia negativa
    continue when v_delta = 0;
    insert into ajustes(bodega_id, lote_id, producto_id, tipo, cantidad, motivo, usuario)
    values (c.bodega_id, d.lote_id, d.producto_id, case when v_delta > 0 then 'positivo' else 'negativo' end::tipo_ajuste,
            abs(v_delta), 'Conteo físico ' || c.numero, app_email()) returning id into v_aj;
    perform mover_lote(d.lote_id, v_delta, case when v_delta > 0 then 'ajuste_positivo' else 'ajuste_negativo' end::tipo_movimiento,
                       'conteo', c.id, 'Conteo físico ' || c.numero);
    n := n + 1;
  end loop;
  update conteos set estado = 'aplicado', aprobado_por = app_email(), aprobado_at = now(), obs_aprobacion = p_obs where id = p_conteo;
  return jsonb_build_object('ajustes', n);
end $$;

create or replace function anular_conteo(p_conteo bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare c conteos;
begin
  select * into c from conteos where id = p_conteo for update;
  perform exigir(found and c.estado in ('en_proceso','pendiente_aprobacion'), 'El conteo ya fue cerrado');
  perform exigir(es_admin() or puede_operar_bodega(c.bodega_id), 'No tiene permiso sobre esta bodega');
  update conteos set estado = 'anulado', obs_aprobacion = p_motivo, aprobado_por = app_email(), aprobado_at = now()
   where id = p_conteo;
end $$;

-- 3. Kardex -------------------------------------------------------------------
create or replace view v_kardex with (security_invoker = true) as
select m.id, m.fecha, (m.fecha at time zone 'America/El_Salvador')::date as dia, m.tipo,
       case m.tipo when 'entrada' then 'Entrada' when 'salida' then 'Salida' when 'anulacion_salida' then 'Anulación de salida'
         when 'traslado_envio' then 'Traslado enviado' when 'traslado_recepcion' then 'Traslado recibido'
         when 'traslado_devolucion_origen' then 'Faltante devuelto al origen' when 'ajuste_positivo' then 'Ajuste +'
         when 'ajuste_negativo' then 'Ajuste −' when 'devolucion_reingreso' then 'Devolución reingresada'
         when 'devolucion_averia' then 'Devolución a avería' when 'carga_inicial' then 'Saldo migrado de SIFAR'
         when 'anulacion_traslado' then 'Anulación de traslado' end as movimiento,
       m.cantidad, m.saldo_lote,
       case m.documento when 'salida' then (select numero from salidas where id = m.documento_id)
                        when 'traslado' then (select numero from traslados where id = m.documento_id)
                        when 'factura' then (select coalesce(numero, 'Factura ' || id) from facturas where id = m.documento_id)
                        when 'ajuste' then 'Ajuste ' || m.documento_id
                        when 'devolucion' then 'Devolución ' || m.documento_id
                        when 'conteo' then (select numero from conteos where id = m.documento_id) end as documento,
       m.usuario, m.observacion,
       p.id as producto_id, p.codigo, p.nombre_comercial, l.id as lote_id, l.numero_lote, l.fecha_vencimiento,
       s.id as sede_id, s.nombre as sede, b.id as bodega_id, b.nombre as bodega
  from movimientos m
  join productos p on p.id = m.producto_id
  join lotes l on l.id = m.lote_id
  join bodegas b on b.id = m.bodega_id
  join sedes s on s.id = b.sede_id;

