-- 7. Tablero de consumo ---------------------------------------------------------
create or replace view v_consumo_diario with (security_invoker = true) as
select s.fecha, date_trunc('month', s.fecha)::date as mes,
       case when extract(day from s.fecha) <= 15 then 1 else 2 end as quincena,
       se.id as sede_id, se.nombre as sede, b.tipo as tipo_bodega, p.tipo as tipo_producto,
       coalesce(f.nombre, 'SIN FAMILIA') as familia, coalesce(pr.nombre, 'SIN PROVEEDOR') as proveedor,
       count(distinct s.id) as despachos,
       count(distinct coalesce(s.dui, s.expediente)) filter (where s.tipo = 'beneficiario') as beneficiarios,
       sum(sd.cantidad) as unidades,
       round(sum(sd.cantidad * coalesce(l.precio_unitario, 0)), 2) as monto
  from salidas s
  join salida_detalle sd on sd.salida_id = s.id
  join productos p on p.id = sd.producto_id
  join bodegas b on b.id = s.bodega_id
  join sedes se on se.id = b.sede_id
  left join lotes l on l.id = sd.lote_id
  left join proveedores pr on pr.id = l.proveedor_id
  left join familias f on f.id = p.familia_id
 where s.estado = 'confirmada'
 group by 1, 2, 3, 4, 5, 6, 7, 8, 9;

create or replace view v_consumo_producto with (security_invoker = true) as
select date_trunc('month', s.fecha)::date as mes, se.nombre as sede, p.id as producto_id, p.codigo, p.nombre_comercial,
       p.principio_activo, p.tipo, sum(sd.cantidad) as unidades,
       round(sum(sd.cantidad * coalesce(l.precio_unitario, 0)), 2) as monto,
       count(distinct s.id) as despachos
  from salidas s
  join salida_detalle sd on sd.salida_id = s.id
  join productos p on p.id = sd.producto_id
  join bodegas b on b.id = s.bodega_id
  join sedes se on se.id = b.sede_id
  left join lotes l on l.id = sd.lote_id
 where s.estado = 'confirmada'
 group by 1, 2, 3;

