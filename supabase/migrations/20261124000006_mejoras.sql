  id               bigint generated by default as identity primary key,
  conteo_id        bigint not null references conteos(id) on delete cascade,
  lote_id          bigint not null references lotes(id),
  producto_id      bigint not null references productos(id),
  cantidad_sistema numeric(14,2) not null,
  cantidad_fisica  numeric(14,2),
  diferencia       numeric(14,2) generated always as (cantidad_fisica - cantidad_sistema) stored,
  contado_por      text,
  contado_at       timestamptz,
  observacion      text,
  unique (conteo_id, lote_id)
);
create index on conteo_detalle (lote_id);
