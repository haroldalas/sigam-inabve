create or replace function auditar() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_antes jsonb; v_despues jsonb; v_campos text[]; v_reg text;
begin
  if tg_op <> 'INSERT' then v_antes := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_despues := to_jsonb(new); end if;
  if tg_op = 'UPDATE' then
    select array_agg(k) into v_campos from jsonb_object_keys(v_despues) k
     where v_despues->k is distinct from v_antes->k and k not in ('modificado_at','modificado_por','ultimo_acceso');
    if v_campos is null then return new; end if;
  end if;
  v_reg := coalesce(v_despues, v_antes) ->> coalesce(tg_argv[0], 'id');
  insert into auditoria(usuario, tabla, operacion, registro, antes, despues, campos)
  values (coalesce(app_email(), current_user), tg_table_name, tg_op, v_reg, v_antes, v_despues, v_campos);
  return coalesce(new, old);
end $$;

