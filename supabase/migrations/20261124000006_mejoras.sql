-- p_filas: [{fecha, sede, codigo, cantidad, factura, lote, dui, contrato, ...resto}]
create or replace function importar_despachos(p_archivo text, p_filas jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_id bigint; n int; sin int;
begin
  perform exigir(es_admin(), 'Solo un administrador carga el Excel de despachos');
  perform exigir(jsonb_array_length(coalesce(p_filas,'[]')) > 0, 'El archivo no tiene filas');
  insert into importaciones_despacho(archivo, cargado_por) values (p_archivo, app_email()) returning id into v_id;
  insert into despachos_importados(importacion_id, fecha, sede_id, codigo, producto_id, cantidad, factura, numero_lote, dui, contrato, fila)
  select v_id, nullif(x->>'fecha','')::date,
         (select id from sedes s where upper(s.nombre) = upper(trim(x->>'sede')) or upper(s.codigo) = upper(trim(x->>'sede'))
                                     or upper(s.nombre_sivet) = upper(trim(x->>'sede')) limit 1),
         trim(x->>'codigo'), (select id from productos p where p.codigo = trim(x->>'codigo') limit 1),
         (x->>'cantidad')::numeric, nullif(trim(x->>'factura'),''), nullif(trim(x->>'lote'),''),
         nullif(regexp_replace(coalesce(x->>'dui',''),'\D','','g'),''), nullif(trim(x->>'contrato'),''), x
    from jsonb_array_elements(p_filas) x
   where nullif(x->>'cantidad','') is not null and (x->>'cantidad')::numeric <> 0;
  get diagnostics n = row_count;
  select count(*) into sin from despachos_importados where importacion_id = v_id and producto_id is null;
  update importaciones_despacho set filas = n, filas_sin_producto = sin,
         desde = (select min(fecha) from despachos_importados where importacion_id = v_id),
         hasta = (select max(fecha) from despachos_importados where importacion_id = v_id)
   where id = v_id;
  return jsonb_build_object('importacion_id', v_id, 'filas', n, 'sin_producto', sin);
end $$;

create or replace function eliminar_importacion(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform exigir(es_admin(), 'Solo un administrador elimina cargas');
  delete from importaciones_despacho where id = p_id;
end $$;

-- Reparto de lo despachado (Excel) entre facturas:
--   1) filas con número de factura → a esa factura
--   2) el resto → por producto, a la factura más antigua con saldo (primero en entrar)
create or replace view v_liquidacion_excel_detalle with (security_invoker = true) as
with lineas as (
  select fd.id as factura_detalle_id, fd.factura_id, fd.producto_id, fd.cantidad, fa.fecha_factura, fa.numero_sivet
    from factura_detalle fd join facturas fa on fa.id = fd.factura_id join proveedores pr on pr.id = fa.proveedor_id
   where fa.estado = 'confirmada' and not pr.es_carga_inicial),
directo as (
  select l.factura_detalle_id, sum(di.cantidad) as cant
    from despachos_importados di
    join lineas l on l.producto_id = di.producto_id
     and l.numero_sivet = lpad(right(regexp_replace(di.factura,'\D','','g'),6),6,'0')
   where di.factura is not null
   group by 1),
sin_factura as (
  select di.producto_id, sum(di.cantidad) as cant from despachos_importados di
   where di.producto_id is not null and (di.factura is null or not exists (
     select 1 from lineas l where l.producto_id = di.producto_id
        and l.numero_sivet = lpad(right(regexp_replace(di.factura,'\D','','g'),6),6,'0')))
   group by 1),
saldo as (
  select l.*, greatest(l.cantidad - coalesce(d.cant,0), 0) as saldo,
         sum(greatest(l.cantidad - coalesce(d.cant,0), 0)) over (partition by l.producto_id order by l.fecha_factura nulls last, l.factura_detalle_id
                                                                rows between unbounded preceding and current row) as acum
    from lineas l left join directo d on d.factura_detalle_id = l.factura_detalle_id)
select s.factura_detalle_id, s.factura_id, s.producto_id, s.cantidad as comprado,
       coalesce(d.cant,0) + greatest(least(s.saldo, coalesce(sf.cant,0) - (s.acum - s.saldo)), 0) as entregado
  from saldo s
  left join directo d on d.factura_detalle_id = s.factura_detalle_id
  left join sin_factura sf on sf.producto_id = s.producto_id;

create or replace view v_liquidacion_excel with (security_invoker = true) as
select fa.id as factura_id, fa.numero, fa.numero_sivet, fa.fecha_factura, pr.nombre as proveedor,
       count(*) as productos, sum(x.comprado) as unidades_compradas, sum(least(x.entregado, x.comprado)) as unidades_entregadas,
       round(sum(x.comprado * fd.precio_unitario), 2) as monto_factura,
       round(sum(least(x.entregado, x.comprado) * fd.precio_unitario), 2) as monto_entregado,
       round(100.0 * sum(least(x.entregado, x.comprado)) / nullif(sum(x.comprado),0), 1) as porcentaje_entregado,
       bool_and(x.entregado >= x.comprado) as lista_para_liquidar,
       fa.estado_liquidacion, fa.liquidacion_fecha, fa.liquidacion_por, fa.liquidacion_obs
  from v_liquidacion_excel_detalle x
  join factura_detalle fd on fd.id = x.factura_detalle_id
  join facturas fa on fa.id = x.factura_id
  join proveedores pr on pr.id = fa.proveedor_id
 group by fa.id, pr.nombre;

