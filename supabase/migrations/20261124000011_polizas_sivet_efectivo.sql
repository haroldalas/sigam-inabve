-- ---------------------------------------------------------------- pólizas
create type estado_poliza as enum ('en_revision', 'conforme', 'con_observaciones');

create table polizas (
  id              bigint generated by default as identity primary key,
  numero          text not null,                       -- ej. P050526
  proveedor_id    smallint not null references proveedores(id),
  periodo_desde   date,
  periodo_hasta   date,
  total_monto     numeric(14,2),                       -- totales impresos en la póliza
  total_iva       numeric(14,2),
  total_liquido   numeric(14,2),
  archivo_ruta    text,                                -- Storage: bucket "polizas"
  archivo_nombre  text,
  estado          estado_poliza not null default 'en_revision',
  observaciones   text,
  creado_por      text not null default app_email(),
  creado_at       timestamptz not null default now(),
  revisado_por    text,
  revisado_at     timestamptz,
  unique (proveedor_id, numero)
);

create table poliza_detalle (
  id          bigint generated by default as identity primary key,
  poliza_id   bigint not null references polizas(id) on delete cascade,
  linea       int not null,
  factura     text not null,
  factura6    text generated always as (lpad(right(regexp_replace(factura, '\D', '', 'g'), 6), 6, '0')) stored,
  fecha       date,
  monto       numeric(14,2) not null,
  iva         numeric(14,2),
  liquido     numeric(14,2),
  origen      text not null default 'manual' check (origen in ('ocr', 'manual')),
  observacion text
);
create index on poliza_detalle (poliza_id);
create index on poliza_detalle (factura6);
create index on polizas (proveedor_id);

alter table polizas enable row level security;
alter table poliza_detalle enable row level security;
create policy leer on polizas for select to authenticated using ((select es_admin()));
create policy leer on poliza_detalle for select to authenticated using ((select es_admin()));
grant select on polizas, poliza_detalle to authenticated;
create trigger auditoria after insert or update or delete on polizas for each row execute function auditar();

insert into parametros(clave, valor, descripcion)
values ('poliza_tolerancia', '0.05', 'Diferencia máxima en dólares para considerar que el monto de la póliza coincide con la factura ingresada')
on conflict (clave) do nothing;

-- p = {numero, proveedor_id, periodo_desde, periodo_hasta, total_monto, total_iva, total_liquido,
--      archivo_ruta, archivo_nombre, filas:[{factura, fecha, monto, iva, liquido, origen}]}
create or replace function guardar_poliza(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_prov smallint; n int := 0; f jsonb;
begin
  perform exigir(es_admin(), 'Solo un administrador registra pólizas');
  perform exigir(nullif(trim(p->>'numero'), '') is not null, 'Indique el número de la póliza');
  v_prov := coalesce(nullif(p->>'proveedor_id', '')::smallint, (select id from proveedores where es_cefafa order by id limit 1));
  perform exigir(exists (select 1 from proveedores where id = v_prov), 'Proveedor no válido');
  perform exigir(jsonb_array_length(coalesce(p->'filas', '[]')) > 0, 'La póliza no tiene facturas');
  perform exigir(not exists (select 1 from polizas where proveedor_id = v_prov and numero = upper(trim(p->>'numero'))),
                 'La póliza ' || upper(trim(p->>'numero')) || ' ya está registrada');

  insert into polizas(numero, proveedor_id, periodo_desde, periodo_hasta, total_monto, total_iva, total_liquido,
                      archivo_ruta, archivo_nombre, observaciones)
  values (upper(trim(p->>'numero')), v_prov, nullif(p->>'periodo_desde', '')::date, nullif(p->>'periodo_hasta', '')::date,
          nullif(p->>'total_monto', '')::numeric, nullif(p->>'total_iva', '')::numeric, nullif(p->>'total_liquido', '')::numeric,
          nullif(p->>'archivo_ruta', ''), nullif(p->>'archivo_nombre', ''), nullif(p->>'observaciones', ''))
  returning id into v_id;

  for f in select * from jsonb_array_elements(p->'filas') loop
    n := n + 1;
    perform exigir(nullif(regexp_replace(coalesce(f->>'factura', ''), '\D', '', 'g'), '') is not null,
                   'Línea ' || n || ': falta el número de factura');
    perform exigir(nullif(f->>'monto', '')::numeric > 0, 'Línea ' || n || ': falta el monto facturado');
    insert into poliza_detalle(poliza_id, linea, factura, fecha, monto, iva, liquido, origen)
    values (v_id, n, trim(f->>'factura'), nullif(f->>'fecha', '')::date, (f->>'monto')::numeric,
            nullif(f->>'iva', '')::numeric, nullif(f->>'liquido', '')::numeric,
            case when f->>'origen' = 'ocr' then 'ocr' else 'manual' end);
  end loop;
  return jsonb_build_object('poliza_id', v_id, 'lineas', n);
end $$;

create or replace function revisar_poliza(p_id bigint, p_estado estado_poliza, p_obs text default null) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform exigir(es_admin(), 'Solo un administrador revisa pólizas');
  update polizas set estado = p_estado, observaciones = coalesce(nullif(trim(p_obs), ''), observaciones),
         revisado_por = app_email(), revisado_at = now()
   where id = p_id;
  perform exigir(found, 'Póliza no encontrada');
end $$;

create or replace function observar_linea_poliza(p_detalle bigint, p_obs text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform exigir(es_admin(), 'Solo un administrador revisa pólizas');
  update poliza_detalle set observacion = nullif(trim(p_obs), '') where id = p_detalle;
  perform exigir(found, 'Línea no encontrada');
end $$;

create or replace function eliminar_poliza(p_id bigint) returns text
language plpgsql security definer set search_path = public as $$
declare v_ruta text;
begin
  perform exigir(es_admin(), 'Solo un administrador elimina pólizas');
  delete from polizas where id = p_id returning archivo_ruta into v_ruta;
  perform exigir(found, 'Póliza no encontrada');
  return v_ruta;
end $$;

-- Cruce de cada línea de la póliza con las entradas registradas en SIGAM.
-- Busca la factura del mismo proveedor y número (últimos 6 dígitos, como SIVET);
-- si hay varias con ese número, toma la de fecha más cercana.
create or replace view v_poliza_revision with (security_invoker = true) as
with fac as (
  select f.id, f.proveedor_id, f.numero, f.numero_sivet, f.fecha_factura, f.estado, f.bodega_id,
         round(coalesce(sum(d.cantidad * d.precio_unitario), 0), 2) as monto_sigam, count(d.id) as productos
    from facturas f left join factura_detalle d on d.factura_id = f.id
   group by f.id
), cruce as (
  select pd.*, po.numero as poliza, po.proveedor_id, m.id as factura_id, m.numero as factura_sigam, m.fecha_factura as fecha_sigam,
         m.estado as estado_sigam, m.monto_sigam, m.productos, b.nombre as bodega_entrada,
         (select count(*) from poliza_detalle x join polizas y on y.id = x.poliza_id
           where x.factura6 = pd.factura6 and y.proveedor_id = po.proveedor_id and x.id <> pd.id) as veces_en_otras
    from poliza_detalle pd
    join polizas po on po.id = pd.poliza_id
    left join lateral (select * from fac
                        where fac.proveedor_id = po.proveedor_id and fac.numero_sivet = pd.factura6
                        order by (fac.estado = 'confirmada') desc,
                                 abs(coalesce(fac.fecha_factura, pd.fecha, current_date) - coalesce(pd.fecha, fac.fecha_factura, current_date)), fac.id
                        limit 1) m on true
    left join bodegas b on b.id = m.bodega_id
)
select c.id, c.poliza_id, c.poliza, c.linea, c.factura, c.factura6, c.fecha, c.monto, c.iva, c.liquido, c.origen, c.observacion,
       c.factura_id, c.factura_sigam, c.fecha_sigam, c.monto_sigam, c.productos, c.bodega_entrada,
       round(c.monto - c.monto_sigam, 2) as diferencia, c.veces_en_otras,
       case
         when c.factura_id is null then 'no_ingresada'
         when c.estado_sigam = 'anulada' then 'anulada_en_sigam'
         when c.fecha is not null and c.fecha_sigam is not null and abs(c.fecha - c.fecha_sigam) > 45 then 'fecha_distinta'
         when abs(c.monto - c.monto_sigam) > parametro_num('poliza_tolerancia', 0.05) then 'monto_distinto'
         else 'coincide'
       end as resultado
  from cruce c;
grant select on v_poliza_revision to authenticated;

create or replace view v_polizas with (security_invoker = true) as
select po.id, po.numero, pr.nombre as proveedor, po.periodo_desde, po.periodo_hasta, po.estado,
       po.total_monto, po.total_iva, po.total_liquido, po.archivo_ruta, po.archivo_nombre, po.observaciones,
       po.creado_por, po.creado_at, po.revisado_por, po.revisado_at,
       count(r.id) as facturas, coalesce(sum(r.monto), 0) as suma_monto,
       count(*) filter (where r.resultado = 'coincide') as coinciden,
       count(*) filter (where r.resultado = 'monto_distinto') as monto_distinto,
       count(*) filter (where r.resultado in ('no_ingresada', 'fecha_distinta', 'anulada_en_sigam')) as no_ingresadas,
       count(*) filter (where r.veces_en_otras > 0) as repetidas,
       coalesce(sum(r.monto) filter (where r.resultado <> 'coincide'), 0) as monto_observado
  from polizas po join proveedores pr on pr.id = po.proveedor_id
  left join v_poliza_revision r on r.poliza_id = po.id
 group by po.id, pr.nombre;
grant select on v_polizas to authenticated;

-- Facturas ingresadas en SIGAM dentro del período de una póliza que no aparecen en ninguna póliza
create or replace view v_facturas_sin_poliza with (security_invoker = true) as
select po.id as poliza_id, f.id as factura_id, f.numero, f.numero_sivet, f.fecha_factura, b.nombre as bodega,
       round(coalesce(sum(d.cantidad * d.precio_unitario), 0), 2) as monto_sigam
  from polizas po
  join facturas f on f.proveedor_id = po.proveedor_id and f.estado = 'confirmada'
                 and f.fecha_factura between po.periodo_desde and po.periodo_hasta
  join bodegas b on b.id = f.bodega_id
  left join factura_detalle d on d.factura_id = f.id
 where not exists (select 1 from poliza_detalle x join polizas y on y.id = x.poliza_id
                    where y.proveedor_id = po.proveedor_id and x.factura6 = f.numero_sivet)
 group by po.id, f.id, b.nombre;
grant select on v_facturas_sin_poliza to authenticated;

