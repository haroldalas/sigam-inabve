-- =============================================================================
-- SIGAM-INABVE · 010 · Conciliación de existencias con SIVET
-- SIVET manda. Cada contrato de SIVET (proveedor × sede × tipo) se descarga en
-- Excel ("DetallesContrato"): una fila por línea de factura con su Stock.
-- Esta función deja las existencias de la sede iguales a SIVET:
--   * Bodega Central y Pequeña Cirugía NO se tocan (conservan lo de SIGAM) y su
--     existencia se descuenta del stock de SIVET.
--   * Lo que resta se reparte en Despacho de Medicamentos, Almacén de Insumos y
--     Campo de la sede, sobre los lotes que ya existen (misma factura primero,
--     se conservan los de vencimiento más lejano, como si se hubiera despachado PVPS).
--   * Si falta, se suma al lote de la misma factura o se crea uno nuevo en el
--     Despacho (medicamentos) o Almacén (insumos) de la sede.
--   * Lotes del contrato que SIVET ya no tiene quedan en cero.
-- Cada cambio queda como movimiento de ajuste con documento 'conciliacion'.
-- p_aplicar = false → solo vista previa (no cambia nada).
-- p_filas = [{codigo, producto, factura, stock, precio, fecha}]
-- =============================================================================

create table conciliaciones (
  id           bigint generated by default as identity primary key,
  contrato_id  smallint not null references contratos(id),
  archivo      text,
  usuario      text not null default app_email(),
  creado_at    timestamptz not null default now(),
  resumen      jsonb not null,
  detalle      jsonb not null
);
create index on conciliaciones (contrato_id, creado_at desc);
alter table conciliaciones enable row level security;
create policy leer on conciliaciones for select to authenticated using ((select es_admin()));

create or replace function conciliar_sivet(p_contrato smallint, p_filas jsonb, p_aplicar boolean default false,
                                           p_archivo text default null)
returns jsonb language plpgsql security definer set search_path = public set client_min_messages = warning as $$
declare
  v_c contratos; v_def smallint; v_carga smallint; v_id bigint; rs record; rl record; rt record;
  rem numeric; tomar numeric; v_lote bigint; v_res jsonb; v_det jsonb; v_nf jsonb;
  v_nuevos int := 0; v_sinvenc int := 0;
begin
  perform exigir(es_admin(), 'Solo un administrador puede conciliar existencias con SIVET');
  select * into v_c from contratos where id = p_contrato;
  perform exigir(found, 'Contrato no válido');
  perform exigir(jsonb_typeof(p_filas) = 'array' and jsonb_array_length(p_filas) > 0, 'El archivo no tiene filas');
  select id into v_def from bodegas
   where sede_id = v_c.sede_id and activa
     and tipo = case when v_c.tipo = 'medicamento' then 'despacho_medicamentos' else 'almacen_insumos' end::tipo_bodega
   order by id limit 1;
  perform exigir(v_def is not null, 'La sede no tiene bodega de despacho/almacén');
  select id into v_carga from proveedores where es_carga_inicial order by id limit 1;

  -- 1. Filas del archivo -------------------------------------------------------
  drop table if exists _f, _s, _l, _r;
  create temp table _f on commit drop as
  select row_number() over () fila, nullif(trim(x.codigo),'') codigo, trim(x.producto) producto,
         case when regexp_replace(coalesce(x.factura,''),'\D','','g') = '' then null
              else lpad(right(regexp_replace(x.factura,'\D','','g'),6),6,'0') end factura,
         coalesce(nullif(regexp_replace(x.stock,'[^0-9.\-]','','g'),'')::numeric, 0) stock,
         nullif(regexp_replace(coalesce(x.precio,''),'[^0-9.]','','g'),'')::numeric precio,
         case when x.fecha ~ '^\d{2}-\d{2}-\d{4}$' then to_date(x.fecha,'DD-MM-YYYY')
              when x.fecha ~ '^\d{4}-\d{2}-\d{2}' then left(x.fecha,10)::date end fecha,
         null::bigint producto_id
    from jsonb_to_recordset(p_filas) as x(codigo text, producto text, factura text, stock text, precio text, fecha text);
  perform exigir(not exists (select 1 from _f where stock < 0), 'El archivo tiene existencias negativas');

  update _f set producto_id = (select p.id from productos p
                                where p.codigo in (_f.codigo, replace(_f.codigo,'-',''''), replace(_f.codigo,'''','-'))
                                order by (p.codigo = _f.codigo) desc, p.activo desc, p.id limit 1)
   where codigo is not null;
  update _f set producto_id = (select p.id from productos p where upper(trim(p.nombre_comercial)) = upper(_f.producto)
                                order by p.activo desc, p.id limit 1)
   where producto_id is null and producto is not null;

  create temp table _s on commit drop as
  select producto_id, factura, sum(stock) stock, max(precio) precio, min(fecha) fecha,
         0::numeric conservado, 0::numeric objetivo, 0::numeric pendiente
    from _f where producto_id is not null group by producto_id, factura;

  -- 2. Lotes de la sede dentro del alcance del contrato ------------------------
  create temp table _l on commit drop as
  select l.id, l.producto_id, l.bodega_id, b.tipo btipo, l.disponible, l.fecha_vencimiento, l.proveedor_id,
         f.numero_sivet factura, b.tipo in ('central','pequena_cirugia') conservar, 0::numeric nuevo,
         coalesce(l.proveedor_id = v_carga, true) sin_contrato
    from lotes l join bodegas b on b.id = l.bodega_id join productos p on p.id = l.producto_id
    left join factura_detalle d on d.id = l.factura_detalle_id left join facturas f on f.id = d.factura_id
   where b.sede_id = v_c.sede_id
     and b.tipo in ('central','despacho_medicamentos','almacen_insumos','pequena_cirugia','campo')
     and ((l.proveedor_id = v_c.proveedor_id and (p.tipo = v_c.tipo or l.producto_id in (select producto_id from _s)))
          or (coalesce(l.proveedor_id = v_carga, true) and l.disponible > 0 and l.producto_id in (select producto_id from _s)));
  if p_aplicar then
    perform 1 from lotes where id in (select id from _l) for update;
  end if;

  -- 3. Lo que conservan Central y Pequeña Cirugía se descuenta de SIVET --------
  update _s set conservado = least(stock, coalesce((select sum(disponible) from _l
                                         where conservar and _l.producto_id = _s.producto_id
                                           and _l.factura is not distinct from _s.factura), 0));
  update _s set objetivo = greatest(stock - conservado, 0);
  for rt in select producto_id, sum(disponible) - coalesce((select sum(conservado) from _s where _s.producto_id = k.producto_id),0) resto
             from _l k where conservar group by producto_id loop
    rem := rt.resto;
    for rs in select * from _s where producto_id = rt.producto_id and objetivo > 0
              order by fecha nulls last, factura nulls last loop
      exit when rem <= 0;
      tomar := least(rs.objetivo, rem);
      update _s set objetivo = objetivo - tomar, conservado = conservado + tomar
       where producto_id = rs.producto_id and factura is not distinct from rs.factura;
      rem := rem - tomar;
    end loop;
  end loop;
  update _s set pendiente = objetivo;

  -- 4. Reparto sobre lotes existentes (no conservados) ------------------------
  -- 4a. misma factura; se conserva primero el de vencimiento más lejano
  for rs in select * from _s where pendiente > 0 order by producto_id, fecha nulls last loop
    rem := rs.pendiente;
    for rl in select * from _l where not conservar and producto_id = rs.producto_id and factura = rs.factura
              order by fecha_vencimiento desc nulls last, (bodega_id = v_def) desc, id loop
      exit when rem <= 0;
      tomar := least(rl.disponible - rl.nuevo, rem);
      if tomar > 0 then update _l set nuevo = nuevo + tomar where id = rl.id; rem := rem - tomar; end if;
    end loop;
    update _s set pendiente = rem where producto_id = rs.producto_id and factura is not distinct from rs.factura;
  end loop;
  -- 4b. lotes del mismo producto cuya factura no está en SIVET (o sin factura); carga inicial al final
  for rs in select * from _s where pendiente > 0 order by producto_id, fecha nulls last loop
    rem := rs.pendiente;
    for rl in select * from _l k where not conservar and producto_id = rs.producto_id
                and (factura is null or not exists (select 1 from _s x where x.producto_id = k.producto_id and x.factura = k.factura))
              order by sin_contrato, fecha_vencimiento desc nulls last, (bodega_id = v_def) desc, id loop
      exit when rem <= 0;
      tomar := least(rl.disponible - rl.nuevo, rem);
      if tomar > 0 then update _l set nuevo = nuevo + tomar where id = rl.id; rem := rem - tomar; end if;
    end loop;
    update _s set pendiente = rem where producto_id = rs.producto_id and factura is not distinct from rs.factura;
  end loop;

  -- 5. Resultado por lote ------------------------------------------------------
  -- Lotes sin contrato (carga inicial o sin proveedor) que no se usaron se dejan como están (pueden ser de otro contrato).
  create temp table _r on commit drop as
  select id, producto_id, bodega_id, disponible actual,
         case when sin_contrato and nuevo = 0 then disponible else nuevo end final,
         sin_contrato and nuevo > 0 usa_carga
    from _l where not conservar;

  -- 6. Vista previa ------------------------------------------------------------
  select coalesce(jsonb_agg(jsonb_build_object(
           'producto_id', z.producto_id, 'codigo', p.codigo, 'producto', p.nombre_comercial, 'tipo', p.tipo,
           'sivet', z.sivet, 'conservado', z.conservado, 'actual', z.actual,
           'final', z.final + z.nuevo, 'diferencia', z.final + z.nuevo - z.actual, 'lotes_nuevos', z.n_nuevos,
           'central_pc', z.guardado, 'central_pc_excede', greatest(z.guardado - z.sivet, 0))
           order by abs(z.final + z.nuevo - z.actual) desc, p.nombre_comercial), '[]')
    into v_det
    from (select producto_id, sum(sivet) sivet, sum(conservado) conservado, sum(actual) actual, sum(final) final,
                 sum(nuevo) nuevo, sum(n_nuevos)::int n_nuevos, sum(guardado) guardado
            from (select producto_id, stock sivet, conservado, 0 actual, 0 final, pendiente nuevo,
                         (pendiente > 0)::int n_nuevos, 0 guardado from _s
                  union all
                  select producto_id, 0, 0, actual, final, 0, 0, 0 from _r
                  union all
                  select producto_id, 0, 0, 0, 0, 0, 0, disponible from _l where conservar) u
           group by producto_id) z
    join productos p on p.id = z.producto_id
   where z.sivet <> 0 or z.actual <> 0 or z.final + z.nuevo <> 0 or z.guardado <> 0;

  select coalesce(jsonb_agg(jsonb_build_object('fila', fila + 1, 'codigo', codigo, 'producto', producto,
                                               'factura', factura, 'stock', stock) order by fila), '[]')
    into v_nf from _f where producto_id is null and stock > 0;

  v_res := jsonb_build_object(
    'contrato', v_c.nombre_sivet,
    'filas', (select count(*) from _f),
    'sivet_total', (select coalesce(sum(stock),0) from _f),
    'no_encontrado_total', (select coalesce(sum(stock),0) from _f where producto_id is null),
    'conservado_total', (select coalesce(sum(disponible),0) from _l where conservar),
    'conservado_excede', (select coalesce(sum(disponible),0) from _l where conservar) - (select coalesce(sum(conservado),0) from _s),
    'actual_total', (select coalesce(sum(actual),0) from _r),
    'final_total', (select coalesce(sum(final),0) from _r) + (select coalesce(sum(pendiente),0) from _s),
    'aumenta', (select coalesce(sum(final - actual),0) from _r where final > actual) + (select coalesce(sum(pendiente),0) from _s),
    'disminuye', (select coalesce(sum(actual - final),0) from _r where final < actual),
    'productos_cambian', (select count(*) from jsonb_array_elements(v_det) e where (e->>'diferencia')::numeric <> 0),
    'lotes_nuevos', (select count(*) from _s where pendiente > 0),
    'carga_inicial_sin_usar', (select coalesce(sum(final),0) from _r r join _l k using (id)
                                where k.sin_contrato and not r.usa_carga),
    'no_encontrados', v_nf);

  if not p_aplicar then
    return v_res || jsonb_build_object('aplicado', false, 'detalle', v_det);
  end if;

  -- 7. Aplicar -----------------------------------------------------------------
  insert into conciliaciones(contrato_id, archivo, resumen, detalle)
  values (v_c.id, p_archivo, v_res, v_det) returning id into v_id;

  for rl in select * from _r where final <> actual loop
    perform mover_lote(rl.id, rl.final - rl.actual,
                       case when rl.final > rl.actual then 'ajuste_positivo' else 'ajuste_negativo' end::tipo_movimiento,
                       'conciliacion', v_id, 'Conciliación con SIVET · ' || v_c.nombre_sivet);
  end loop;
  update lotes set proveedor_id = v_c.proveedor_id where id in (select id from _r where usa_carga);

  -- faltante: se suma al lote de la misma factura o se crea uno nuevo
  for rs in select * from _s where pendiente > 0 loop
    select k.id into v_lote from _l k where not conservar and k.producto_id = rs.producto_id and k.factura = rs.factura
     order by (k.bodega_id = v_def) desc, k.fecha_vencimiento desc nulls last, k.id limit 1;
    if v_lote is null then
      -- copia de un lote de la misma factura en cualquier bodega (conserva lote y vencimiento)
      select l2.id into v_lote from lotes l2 join factura_detalle d on d.id = l2.factura_detalle_id
        join facturas f on f.id = d.factura_id
       where l2.producto_id = rs.producto_id and f.proveedor_id = v_c.proveedor_id and f.numero_sivet = rs.factura
       order by l2.id limit 1;
      if v_lote is not null then
        v_lote := lote_en_bodega(v_lote, v_def);
      else
        insert into lotes(factura_detalle_id, producto_id, bodega_id, proveedor_id, numero_lote, fecha_vencimiento,
                          precio_unitario, cantidad_inicial, disponible, estado)
        select d.id, rs.producto_id, v_def, v_c.proveedor_id,
               coalesce(d.numero_lote, 'SIVET-' || coalesce(rs.factura,'S/F')), d.fecha_vencimiento,
               coalesce(d.precio_unitario, rs.precio, 0), rs.pendiente, 0, 'agotado'
          from (select 1) one
          left join lateral (select d.* from factura_detalle d join facturas f on f.id = d.factura_id
                              where d.producto_id = rs.producto_id and f.proveedor_id = v_c.proveedor_id
                                and f.numero_sivet = rs.factura and f.estado = 'confirmada'
                              order by d.id limit 1) d on true
        returning id into v_lote;
        v_nuevos := v_nuevos + 1;
        if (select fecha_vencimiento is null from lotes where id = v_lote) then v_sinvenc := v_sinvenc + 1; end if;
      end if;
    end if;
    update lotes set proveedor_id = v_c.proveedor_id where id = v_lote and (proveedor_id is null or proveedor_id = v_carga);
    perform mover_lote(v_lote, rs.pendiente, 'ajuste_positivo', 'conciliacion', v_id,
                       'Conciliación con SIVET · ' || v_c.nombre_sivet || coalesce(' · factura ' || rs.factura, ''));
    v_lote := null;
  end loop;

  v_res := v_res || jsonb_build_object('aplicado', true, 'conciliacion_id', v_id,
                                       'lotes_creados', v_nuevos, 'lotes_sin_vencimiento', v_sinvenc);
  update conciliaciones set resumen = v_res where id = v_id;
  return v_res || jsonb_build_object('detalle', v_det);
end $$;

revoke all on function conciliar_sivet(smallint, jsonb, boolean, text) from public, anon;
grant execute on function conciliar_sivet(smallint, jsonb, boolean, text) to authenticated;
grant select on conciliaciones to authenticated;

-- Historial legible
create or replace view v_conciliaciones with (security_invoker = true) as
select k.id, k.creado_at, k.usuario, k.archivo, c.nombre_sivet contrato, s.nombre sede,
       (k.resumen->>'sivet_total')::numeric sivet_total, (k.resumen->>'actual_total')::numeric antes,
       (k.resumen->>'final_total')::numeric despues, (k.resumen->>'aumenta')::numeric aumenta,
       (k.resumen->>'disminuye')::numeric disminuye, (k.resumen->>'lotes_creados')::int lotes_creados,
       jsonb_array_length(coalesce(k.resumen->'no_encontrados','[]')) no_encontrados
  from conciliaciones k join contratos c on c.id = k.contrato_id join sedes s on s.id = c.sede_id;
grant select on v_conciliaciones to authenticated;

-- El kardex muestra el documento de conciliación
create or replace view v_kardex with (security_invoker = true) as
select m.id, m.fecha, (m.fecha at time zone 'America/El_Salvador')::date as dia, m.tipo,
       case m.tipo when 'entrada' then 'Entrada' when 'salida' then 'Salida' when 'anulacion_salida' then 'Anulación de salida'
         when 'traslado_envio' then 'Traslado enviado' when 'traslado_recepcion' then 'Traslado recibido'
         when 'traslado_devolucion_origen' then 'Faltante devuelto al origen' when 'ajuste_positivo' then 'Ajuste +'
         when 'ajuste_negativo' then 'Ajuste −' when 'devolucion_reingreso' then 'Devolución reingresada'
         when 'devolucion_averia' then 'Devolución a avería' when 'carga_inicial' then 'Saldo migrado de SIFAR'
         when 'anulacion_traslado' then 'Anulación de traslado' end as movimiento,
       m.cantidad, m.saldo_lote,
       case m.documento when 'salida' then (select numero from salidas where id = m.documento_id)
                        when 'traslado' then (select numero from traslados where id = m.documento_id)
                        when 'factura' then (select coalesce(numero, 'Factura ' || id) from facturas where id = m.documento_id)
                        when 'ajuste' then 'Ajuste ' || m.documento_id
                        when 'devolucion' then 'Devolución ' || m.documento_id
                        when 'conteo' then (select numero from conteos where id = m.documento_id)
                        when 'conciliacion' then 'Conciliación SIVET ' || m.documento_id end as documento,
       m.usuario, m.observacion,
       p.id as producto_id, p.codigo, p.nombre_comercial, l.id as lote_id, l.numero_lote, l.fecha_vencimiento,
       s.id as sede_id, s.nombre as sede, b.id as bodega_id, b.nombre as bodega
  from movimientos m
  join productos p on p.id = m.producto_id
  join lotes l on l.id = m.lote_id
  join bodegas b on b.id = m.bodega_id
  join sedes s on s.id = b.sede_id;
