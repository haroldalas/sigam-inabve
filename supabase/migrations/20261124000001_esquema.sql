set check_function_bodies = off;

-- ---------------------------------------------------------------------------
-- Tipos
-- ---------------------------------------------------------------------------
create type rol_usuario      as enum ('administrador','dependiente','consulta');
create type tipo_producto    as enum ('medicamento','insumo');
create type tipo_bodega      as enum ('central','despacho_medicamentos','almacen_insumos',
                                      'pequena_cirugia','campo','descarte');
create type categoria_aware  as enum ('acceso','precaucion','reserva','no_recomendado','otros');
create type estado_lote      as enum ('activo','bloqueado','cuarentena','agotado');
create type estado_documento as enum ('confirmada','anulada');
create type estado_liquidacion as enum ('pendiente','en_proceso','liquidada');
create type tipo_salida      as enum ('beneficiario','personal','campo','otro');
create type estado_traslado  as enum ('enviado','recibido','con_diferencias','cerrado','anulado');
create type tipo_diferencia  as enum ('faltante','sobrante','producto_no_enviado');
create type estado_diferencia as enum ('pendiente','resuelta');
create type tipo_ajuste      as enum ('positivo','negativo');
create type estado_devolucion as enum ('pendiente','reingresada','averia','rechazada');
create type estado_fisico_devolucion as enum ('completo_sellado','abierto','danado','incompleto');
create type tipo_movimiento  as enum ('entrada','salida','anulacion_salida','traslado_envio',
                                      'traslado_recepcion','traslado_devolucion_origen','ajuste_positivo',
                                      'ajuste_negativo','devolucion_reingreso','devolucion_averia',
                                      'carga_inicial','anulacion_traslado');

-- ---------------------------------------------------------------------------
-- Organización
-- ---------------------------------------------------------------------------
create table sedes (
  id          smallint generated by default as identity primary key,
  codigo      text not null unique,             -- JPII, SM, SA, CH
  nombre      text not null unique,             -- Juan Pablo II, San Miguel...
  nombre_sivet text not null,                    -- como aparece en el nombre de contrato SIVET
  activa      boolean not null default true
);

create table bodegas (
  id               smallint generated by default as identity primary key,
  codigo           text not null unique,
  nombre           text not null,
  sede_id          smallint not null references sedes(id),
  tipo             tipo_bodega not null,
  permite_entradas boolean not null default false, -- solo bodega central
  solo_admin       boolean not null default false, -- Descarte: solo administradores
  activa           boolean not null default true,
  responsable      text,
  correo           text,
  sifar_id         int unique,
  unique (sede_id, tipo, nombre)
);

create table perfiles (
  id           uuid unique references auth.users(id) on delete set null,
  email        text primary key check (email ~* '^[^@]+@inabve\.gob\.sv$'),
  nombre       text not null,
  rol          rol_usuario not null default 'consulta',
  sede_id      smallint references sedes(id),
  activo       boolean not null default false,       -- un administrador lo habilita
  sifar_usuario text,
  creado_at    timestamptz not null default now(),
  ultimo_acceso timestamptz,
  constraint dependiente_con_sede check (rol <> 'dependiente' or sede_id is not null)
);

-- ---------------------------------------------------------------------------
-- Catálogo (los códigos son los mismos de SIVET: no se alteran)
-- ---------------------------------------------------------------------------
create table familias (
  id     smallint generated by default as identity primary key,
  nombre text not null unique,
  activa boolean not null default true
);

create table productos (
  id                bigint generated by default as identity primary key, -- = IDMedicamento SIFAR
  codigo            text unique,                     -- código de barras / código SIVET
  nombre_comercial  text not null,
  principio_activo  text,
  concentracion     text,
  presentacion      text,
  familia_id        smallint references familias(id),
  tipo              tipo_producto not null default 'medicamento',
  aware             categoria_aware,                 -- obligatorio si familia = ANTIBIOTICO (trigger)
  controlado        boolean not null default false,
  cadena_frio       boolean not null default false,
  activo            boolean not null default true,
  motivo_inactividad text,
  creado_at         timestamptz not null default now(),
  creado_por        text,
  modificado_at     timestamptz,
  modificado_por    text
);
create index on productos (familia_id);
create index productos_busqueda on productos using gin (
  to_tsvector('simple', coalesce(nombre_comercial,'')||' '||coalesce(principio_activo,'')||' '||coalesce(codigo,'')));

-- Proveedores = "contratos" en el lenguaje de SIVET (CEFAFA, SUPLIDORES DIVERSOS...)
create table proveedores (
  id            smallint generated by default as identity primary key,
  nombre        text not null unique,
  nombre_sivet  text not null,              -- prefijo del nombre de contrato SIVET
  es_cefafa     boolean not null default false,
  registro_fiscal text,
  telefono      text,
  correo        text,
  activo        boolean not null default true,
  es_carga_inicial boolean not null default false  -- pseudo-proveedor "CARGA INICIAL INVENTARIO" de SIFAR
);

-- Contrato SIVET por proveedor × sede × tipo (número y nombre exacto)
create table contratos (
  id           smallint generated by default as identity primary key,
  numero_sivet int unique,
  proveedor_id smallint not null references proveedores(id),
  sede_id      smallint not null references sedes(id),
  tipo         tipo_producto not null,
  nombre_sivet text not null unique,       -- "CEFAFA - MEDICAMENTOS - SANTA ANA"
  activo       boolean not null default true,
  unique (proveedor_id, sede_id, tipo)
);
create index on contratos (sede_id);

-- ---------------------------------------------------------------------------
-- Entradas (facturas): solo en bodega central
-- ---------------------------------------------------------------------------
create table facturas (
  id               bigint generated by default as identity primary key,
  numero           text,                    -- número completo (DTE u otro)
  numero_sivet     text generated always as (
                     case when numero is null then null
                          else lpad(right(regexp_replace(numero,'\D','','g'),6),6,'0') end) stored,
  fecha_factura    date,
  proveedor_id     smallint not null references proveedores(id),
  bodega_id        smallint not null references bodegas(id),
  acta_recepcion   text,
  observaciones    text,
  estado           estado_documento not null default 'confirmada',
  estado_liquidacion estado_liquidacion not null default 'pendiente',
  liquidacion_fecha date,
  liquidacion_por  text,
  liquidacion_obs  text,
  creado_at        timestamptz not null default now(),
  creado_por       text,
  sifar_id         int unique
);
create index on facturas (proveedor_id);
create index on facturas (bodega_id);
create index on facturas (numero_sivet);

create table factura_detalle (
  id               bigint generated by default as identity primary key,
  factura_id       bigint not null references facturas(id) on delete cascade,
  producto_id      bigint not null references productos(id),
  cantidad         numeric(14,2) not null check (cantidad > 0),
  precio_unitario  numeric(14,4) not null check (precio_unitario >= 0),
  numero_lote      text,
  fecha_vencimiento date,
  sifar_id         int unique
);
create index on factura_detalle (factura_id);
create index on factura_detalle (producto_id);

-- ---------------------------------------------------------------------------
-- Lotes: la existencia vive aquí (una fila por lote y bodega).
-- Un traslado crea en destino una copia que conserva factura_detalle_id,
-- así toda entrega cuenta para la factura original (liquidación).
-- ---------------------------------------------------------------------------
create table lotes (
  id                 bigint generated by default as identity primary key,
  factura_detalle_id bigint references factura_detalle(id),
  producto_id        bigint not null references productos(id),
  bodega_id          smallint not null references bodegas(id),
  proveedor_id       smallint references proveedores(id),
  numero_lote        text,
  fecha_vencimiento  date,
  precio_unitario    numeric(14,4) not null default 0,
  cantidad_inicial   numeric(14,2) not null default 0,
  disponible         numeric(14,2) not null default 0 check (disponible >= 0),
  estado             estado_lote not null default 'activo',
  lote_origen_id     bigint references lotes(id),
  creado_at          timestamptz not null default now(),
  sifar_id           int unique
);
create index on lotes (producto_id, bodega_id);
create index on lotes (bodega_id) where disponible > 0;
create index on lotes (factura_detalle_id);
create index on lotes (proveedor_id);
create index on lotes (lote_origen_id);

-- Kardex: todo cambio de existencia deja un movimiento
create table movimientos (
  id            bigint generated by default as identity primary key,
  fecha         timestamptz not null default now(),
  tipo          tipo_movimiento not null,
  lote_id       bigint not null references lotes(id),
  producto_id   bigint not null references productos(id),
  bodega_id     smallint not null references bodegas(id),
  cantidad      numeric(14,2) not null,          -- + entra / - sale
  saldo_lote    numeric(14,2),
  documento     text,                            -- 'salida', 'traslado', 'factura'...
  documento_id  bigint,
  usuario       text,
  observacion   text
);
create index on movimientos (lote_id);
create index on movimientos (producto_id);
create index on movimientos (documento, documento_id);
create index on movimientos (bodega_id, fecha);

-- ---------------------------------------------------------------------------
-- Salidas (despacho)
-- ---------------------------------------------------------------------------
create table salidas (
  id               bigint generated by default as identity primary key,
  numero           text not null unique,
  fecha            date not null default (now() at time zone 'America/El_Salvador')::date,
  bodega_id        smallint not null references bodegas(id),
  tipo             tipo_salida not null default 'beneficiario',
  dui              text,
  expediente       text,
  persona_recibe   text,         -- salidas a personal (pequeña cirugía)
  persona_solicita text,
  observaciones    text,
  estado           estado_documento not null default 'confirmada',
  anulada_por      text,
  anulada_at       timestamptz,
  motivo_anulacion text,
  creado_at        timestamptz not null default now(),
  creado_por       text,
  sifar_id         int unique,
  constraint salida_beneficiario_identificado check
    (tipo <> 'beneficiario' or dui is not null or expediente is not null or sifar_id is not null),
  constraint salida_personal_con_persona check
    (tipo <> 'personal' or persona_recibe is not null or sifar_id is not null)
);
create index on salidas (bodega_id, fecha);
create index on salidas (dui);

create table salida_detalle (
  id          bigint generated by default as identity primary key,
  salida_id   bigint not null references salidas(id) on delete cascade,
  producto_id bigint not null references productos(id),
  lote_id     bigint references lotes(id),
  cantidad    numeric(14,2) not null check (cantidad > 0),
  sifar_id    int
);
create index on salida_detalle (salida_id);
create index on salida_detalle (lote_id);
create index on salida_detalle (producto_id);

-- ---------------------------------------------------------------------------
-- Traslados entre bodegas / sedes
-- ---------------------------------------------------------------------------
create table traslados (
  id                bigint generated by default as identity primary key,
  numero            text not null unique,
  fecha             date not null default (now() at time zone 'America/El_Salvador')::date,
  bodega_origen_id  smallint not null references bodegas(id),
  bodega_destino_id smallint not null references bodegas(id),
  estado            estado_traslado not null default 'enviado',
  observaciones     text,
  enviado_por       text,
  enviado_at        timestamptz not null default now(),
  recibido_por      text,
  recibido_at       timestamptz,
  anulado_por       text,
  motivo_anulacion  text,
  enviado_sivet     boolean not null default false,  -- ya se mandó a TICS para migrar
  sifar_id          int unique,
  check (bodega_origen_id <> bodega_destino_id)
);
create index on traslados (bodega_destino_id, estado);
create index on traslados (bodega_origen_id);

create table traslado_detalle (
  id                bigint generated by default as identity primary key,
  traslado_id       bigint not null references traslados(id) on delete cascade,
  producto_id       bigint not null references productos(id),
  lote_origen_id    bigint references lotes(id),
  lote_destino_id   bigint references lotes(id),
  cantidad_enviada  numeric(14,2) not null check (cantidad_enviada > 0),
  cantidad_recibida numeric(14,2),
  observacion       text,
  sifar_id          int unique
);
create index on traslado_detalle (traslado_id);
create index on traslado_detalle (producto_id);
create index on traslado_detalle (lote_origen_id);
create index on traslado_detalle (lote_destino_id);

create table traslado_diferencias (
  id                  bigint generated by default as identity primary key,
  traslado_id         bigint not null references traslados(id) on delete cascade,
  traslado_detalle_id bigint references traslado_detalle(id),
  producto_id         bigint not null references productos(id),
  tipo                tipo_diferencia not null,
  cantidad_enviada    numeric(14,2) not null default 0,
  cantidad_recibida   numeric(14,2) not null default 0,
  observacion_sede    text,
  estado              estado_diferencia not null default 'pendiente',
  resolucion          text,
  resuelto_por        text,
  resuelto_at         timestamptz,
  creado_at           timestamptz not null default now()
);
create index on traslado_diferencias (estado);
create index on traslado_diferencias (traslado_id);

-- ---------------------------------------------------------------------------
-- Ajustes y devoluciones
-- ---------------------------------------------------------------------------
create table ajustes (
  id          bigint generated by default as identity primary key,
  fecha       timestamptz not null default now(),
  bodega_id   smallint not null references bodegas(id),
  lote_id     bigint not null references lotes(id),
  producto_id bigint not null references productos(id),
  tipo        tipo_ajuste not null,
  cantidad    numeric(14,2) not null check (cantidad > 0),
  motivo      text not null check (length(trim(motivo)) >= 5),
  usuario     text
);
create index on ajustes (bodega_id);
create index on ajustes (lote_id);

create table devoluciones (
  id              bigint generated by default as identity primary key,
  creado_at       timestamptz not null default now(),
  bodega_id       smallint not null references bodegas(id),
  producto_id     bigint not null references productos(id),
  numero_factura  text not null,
  dui             text not null,
  fecha_receta    date not null,
  cantidad        numeric(14,2) not null check (cantidad > 0),
  motivo          text not null,
  estado_fisico   estado_fisico_devolucion not null,
  observacion     text,
  lote_id         bigint references lotes(id),   -- identificado por factura + producto
  estado          estado_devolucion not null default 'pendiente',
  registrado_por  text,
  validado_por    text,
  validado_at     timestamptz,
  obs_validacion  text
);
create index on devoluciones (estado);
create index on devoluciones (bodega_id);
create index on devoluciones (lote_id);

-- ---------------------------------------------------------------------------
-- Liquidación: despachos importados desde el Excel diario (SIFAR / SIVET)
-- ---------------------------------------------------------------------------
create table importaciones_despacho (
  id          bigint generated by default as identity primary key,
  archivo     text not null,
  cargado_at  timestamptz not null default now(),
  cargado_por text,
  filas       int,
  observaciones text
);

-- Documentos adjuntos (actas de traslado firmadas, comprobantes) en Storage
create table adjuntos (
  id           bigint generated by default as identity primary key,
  entidad      text not null check (entidad in ('traslado','salida','factura','devolucion','ajuste')),
  entidad_id   bigint not null,
  ruta_storage text not null,
  nombre       text not null,
  subido_por   text,
  subido_at    timestamptz not null default now()
);
create index on adjuntos (entidad, entidad_id);

